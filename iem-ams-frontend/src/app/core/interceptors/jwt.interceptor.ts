/**
 * src/app/core/interceptors/jwt.interceptor.ts
 *
 * Functional HTTP Interceptor for Angular 17.
 * - Inspects every outgoing HTTP request
 * - If a JWT token is stored, attaches 'Authorization: Bearer <token>' header
 * - If the server responds with 401 (Unauthorized), automatically logs the user out
 */

import { HttpInterceptorFn, HttpErrorResponse } from '@angular/common/http';
import { inject } from '@angular/core';
import { catchError, throwError } from 'rxjs';
import { AuthService } from '../services/auth.service';

export const jwtInterceptor: HttpInterceptorFn = (req, next) => {
  const authService = inject(AuthService);
  const token = authService.getToken();

  // Clone request with Authorization header if token exists
  let authReq = req;
  if (token) {
    authReq = req.clone({
      setHeaders: {
        Authorization: `Bearer ${token}`
      }
    });
  }

  return next(authReq).pipe(
    catchError((error: HttpErrorResponse) => {
      // 401 Unauthorized means the token expired or is invalid
      if (error.status === 401 && !req.url.includes('/auth/login')) {
        authService.logout();
      }
      return throwError(() => error);
    })
  );
};

